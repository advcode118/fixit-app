import { NextRequest, NextResponse } from 'next/server';
import { AccessibilityIssue } from '@/types';

export const runtime = 'nodejs';

interface CreatePRRequest {
  repo: string;
  files: Array<{
    path: string;
    content: string;
  }>;
  summary: string;
  issues: AccessibilityIssue[];
}

interface GitHubTreeItem {
  path: string;
  mode: '100644';
  type: 'blob';
  sha: string;
}

async function githubRequest(
  endpoint: string,
  token: string,
  options: RequestInit = {}
): Promise<Response> {
  const response = await fetch(`https://api.github.com${endpoint}`, {
    ...options,
    headers: {
      'Authorization': `Bearer ${token}`,
      'Accept': 'application/vnd.github.v3+json',
      'Content-Type': 'application/json',
      'X-GitHub-Api-Version': '2022-11-28',
      ...options.headers,
    },
  });

  return response;
}

function generatePRBody(issues: AccessibilityIssue[], summary: string): string {
  const categoryCounts = {
    accessibility: issues.filter(i => i.category === 'accessibility').length,
    seo: issues.filter(i => i.category === 'seo').length,
  };

  const severityCounts = {
    critical: issues.filter(i => i.severity === 'critical').length,
    serious: issues.filter(i => i.severity === 'serious').length,
    moderate: issues.filter(i => i.severity === 'moderate').length,
    minor: issues.filter(i => i.severity === 'minor').length,
  };

  const fixedIssues = issues.filter(i => i.fix);

  let body = `## 🔧 FixIt Accessibility & SEO Fixes

${summary}

### 📊 Summary

| Metric | Count |
|--------|-------|
| Total Issues Found | ${issues.length} |
| Issues Fixed | ${fixedIssues.length} |
| Accessibility Issues | ${categoryCounts.accessibility} |
| SEO Issues | ${categoryCounts.seo} |

### 🎯 Severity Breakdown

| Severity | Count |
|----------|-------|
| 🔴 Critical | ${severityCounts.critical} |
| 🟠 Serious | ${severityCounts.serious} |
| 🟡 Moderate | ${severityCounts.moderate} |
| 🟢 Minor | ${severityCounts.minor} |

### ✅ Fixes Applied

`;

  for (const issue of fixedIssues) {
    const severity = {
      critical: '🔴',
      serious: '🟠',
      moderate: '🟡',
      minor: '🟢',
    }[issue.severity] || '⚪';

    body += `#### ${severity} ${issue.description}

- **WCAG Rule:** ${issue.wcagRule || 'N/A'}
- **Impact:** ${issue.impact}
- **File:** \`${issue.fix?.file}\`

<details>
<summary>View Fix</summary>

**Before:**
\`\`\`html
${issue.fix?.originalCode}
\`\`\`

**After:**
\`\`\`html
${issue.fix?.fixedCode}
\`\`\`

**Explanation:** ${issue.fix?.explanation}

</details>

---

`;
  }

  body += `
### 🤖 Generated by FixIt

This PR was automatically generated by [FixIt](https://github.com/advcode118/fixit) - an AI-powered accessibility and SEO auditor.

---
*Please review the changes carefully before merging.*
`;

  return body;
}

export async function POST(request: NextRequest) {
  try {
    const body: CreatePRRequest = await request.json();
    const { repo, files, summary, issues } = body;

    if (!repo || !files || files.length === 0) {
      return NextResponse.json(
        { error: 'Repository and files are required' },
        { status: 400 }
      );
    }

    const token = process.env.GITHUB_TOKEN;

    if (!token) {
      return NextResponse.json(
        { error: 'GitHub token not configured. Please set GITHUB_TOKEN environment variable.' },
        { status: 500 }
      );
    }

    const [owner, repoName] = repo.split('/');
    if (!owner || !repoName) {
      return NextResponse.json(
        { error: 'Invalid repository format. Use "owner/repo"' },
        { status: 400 }
      );
    }

    const repoResponse = await githubRequest(`/repos/${owner}/${repoName}`, token);
    if (!repoResponse.ok) {
      const errorData = await repoResponse.json();
      return NextResponse.json(
        { error: `Repository not found or inaccessible: ${errorData.message || 'Unknown error'}` },
        { status: 404 }
      );
    }

    const repoData = await repoResponse.json();
    const defaultBranch = repoData.default_branch || 'main';

    const refResponse = await githubRequest(
      `/repos/${owner}/${repoName}/git/ref/heads/${defaultBranch}`,
      token
    );

    if (!refResponse.ok) {
      return NextResponse.json(
        { error: `Could not get reference for ${defaultBranch} branch` },
        { status: 500 }
      );
    }

    const refData = await refResponse.json();
    const baseSha = refData.object.sha;

    const timestamp = Date.now();
    const branchName = `fixit/auto-fixes-${timestamp}`;

    const createRefResponse = await githubRequest(
      `/repos/${owner}/${repoName}/git/refs`,
      token,
      {
        method: 'POST',
        body: JSON.stringify({
          ref: `refs/heads/${branchName}`,
          sha: baseSha,
        }),
      }
    );

    if (!createRefResponse.ok) {
      const errorData = await createRefResponse.json();
      return NextResponse.json(
        { error: `Failed to create branch: ${errorData.message || 'Unknown error'}` },
        { status: 500 }
      );
    }

    const treeItems: GitHubTreeItem[] = [];

    for (const file of files) {
      const blobResponse = await githubRequest(
        `/repos/${owner}/${repoName}/git/blobs`,
        token,
        {
          method: 'POST',
          body: JSON.stringify({
            content: Buffer.from(file.content).toString('base64'),
            encoding: 'base64',
          }),
        }
      );

      if (!blobResponse.ok) {
        continue;
      }

      const blobData = await blobResponse.json();
      treeItems.push({
        path: file.path,
        mode: '100644',
        type: 'blob',
        sha: blobData.sha,
      });
    }

    if (treeItems.length === 0) {
      return NextResponse.json(
        { error: 'Failed to create any file blobs' },
        { status: 500 }
      );
    }

    const treeResponse = await githubRequest(
      `/repos/${owner}/${repoName}/git/trees`,
      token,
      {
        method: 'POST',
        body: JSON.stringify({
          base_tree: baseSha,
          tree: treeItems,
        }),
      }
    );

    if (!treeResponse.ok) {
      return NextResponse.json(
        { error: 'Failed to create tree' },
        { status: 500 }
      );
    }

    const treeData = await treeResponse.json();

    const fixedCount = issues.filter(i => i.fix).length;
    const commitMessage = `fix: apply ${fixedCount} accessibility and SEO fixes

Automated fixes generated by FixIt:
- ${issues.filter(i => i.severity === 'critical' && i.fix).length} critical issues
- ${issues.filter(i => i.severity === 'serious' && i.fix).length} serious issues
- ${issues.filter(i => i.severity === 'moderate' && i.fix).length} moderate issues
- ${issues.filter(i => i.severity === 'minor' && i.fix).length} minor issues`;

    const commitResponse = await githubRequest(
      `/repos/${owner}/${repoName}/git/commits`,
      token,
      {
        method: 'POST',
        body: JSON.stringify({
          message: commitMessage,
          tree: treeData.sha,
          parents: [baseSha],
        }),
      }
    );

    if (!commitResponse.ok) {
      return NextResponse.json(
        { error: 'Failed to create commit' },
        { status: 500 }
      );
    }

    const commitData = await commitResponse.json();

    const updateRefResponse = await githubRequest(
      `/repos/${owner}/${repoName}/git/refs/heads/${branchName}`,
      token,
      {
        method: 'PATCH',
        body: JSON.stringify({
          sha: commitData.sha,
        }),
      }
    );

    if (!updateRefResponse.ok) {
      return NextResponse.json(
        { error: 'Failed to update branch reference' },
        { status: 500 }
      );
    }

    const prBody = generatePRBody(issues, summary);

    const prResponse = await githubRequest(
      `/repos/${owner}/${repoName}/pulls`,
      token,
      {
        method: 'POST',
        body: JSON.stringify({
          title: `🔧 FixIt: Apply ${fixedCount} accessibility & SEO fixes`,
          head: branchName,
          base: defaultBranch,
          body: prBody,
        }),
      }
    );

    if (!prResponse.ok) {
      const errorData = await prResponse.json();
      return NextResponse.json(
        { error: `Failed to create PR: ${errorData.message || 'Unknown error'}` },
        { status: 500 }
      );
    }

    const prData = await prResponse.json();

    return NextResponse.json({
      success: true,
      prUrl: prData.html_url,
      branch: branchName,
      filesChanged: treeItems.length,
    });
  } catch (error) {
    console.error('Create PR error:', error);
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Unknown error occurred' },
      { status: 500 }
    );
  }
}
